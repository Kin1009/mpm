static bool FindAddins_add(struct AddInList *list, u16 const *path,
                           struct CW_BFile_FileInfo *fileinfo)
{
    u16 *path_copy = PathDuplicate(path, u"\\\\fls0\\");
    if(!path_copy)
        return false;

    struct AddIn *addin = AddInList_extend(list);
    if(!addin) {
        CW_free(path_copy);
        return false;
    }

    addin->path = path_copy;
    addin->filesize = fileinfo->file_size;
    return true;
}

/* Finds all add-ins and any relevant information from the storage memory. The
   given AddInList gets all add-ins found appended to it. Returns the number of
   add-ins found on sucess, or a BFile error code if an error is encountered.
   Note that some add-ins might still have been found even if the return value
   is an error code. */
int FindAddins(struct AddInList *list)
{
    u16 found[0x10a + 1];
    u16 const *pattern = u"\\\\fls0\\*.g3a";
    struct CW_BFile_FileInfo fileinfo;
    int shandle = -1;
    int rc = CW_BFile_FindFirst(pattern, &shandle, found, &fileinfo);
    int total = 0;

    if(rc == -1 /* BFile_EntryNotFound */) {
        CW_BFile_FindClose(shandle);
        return 0;
    }

    while(rc == 0) {
        bool valid = true;

        /* We used to check for BFile_Type_Archived = 0x41 in fileinfo.type
           here. But g3a files generated by add-ins (e.g. decompressed) have
           type 0x01. So instead just exclude folders directly. */
        if(fileinfo.type == 0x00)
            valid = false;
        /* Must have a full g3a header + checksum, at least. */
        if(fileinfo.file_size < 0x7002)
            valid = false;

        // TODO: Known bug: this fails after checking Storage memory in MEMORY
        if(valid && !FindAddins_add(list, found, &fileinfo)) {
            rc = -999;
            break;
        }
        total += valid;
        rc = CW_BFile_FindNext(shandle, found, &fileinfo);
    }

    CW_BFile_FindClose(shandle);
    return rc == -16 /* BFile_EnumerateEnd */ ? total : rc;
}

